// Generates src/styles/palettes.css from scripts/palettes.mjs.
import { writeFileSync } from 'node:fs';
import { DEFAULT_PALETTE, PALETTES, resolved } from './palettes.mjs';

const block = (selector, vars, scheme) => {
  const { wave, ...rest } = vars;
  const lines = Object.entries(rest).map(([k, v]) => `  --${k}: ${v};`);
  lines.push(`  --wave-front: rgb(${wave} / 15%);`, `  --wave-back: rgb(${wave} / 8%);`, `  color-scheme: ${scheme};`);
  if (scheme === 'dark') lines.push('  --shadow-1: none;', '  --shadow-2: 0 12px 40px rgb(0 0 0 / 45%);', '  --overlay: rgb(0 0 0 / 55%);');
  return `${selector} {\n${lines.join('\n')}\n}\n`;
};

let css = '/* Generated by scripts/build-palettes.mjs — edit scripts/palettes.mjs instead. */\n\n';
for (const name of Object.keys(PALETTES)) {
  const isDefault = name === DEFAULT_PALETTE;
  // Also on any element with data-palette (theme swatches preview their own colours).
  const light = (isDefault ? `:root,\n` : '') + `:root[data-palette='${name}'],\n[data-palette='${name}']`;
  const sel = (extra) =>
    (isDefault ? `:root:not([data-palette])${extra},\n` : '') +
    `:root[data-palette='${name}']${extra},\n:root${extra} [data-palette='${name}']`;
  css += block(light, resolved(name, 'light'), 'light') + '\n';
  css += `@media (prefers-color-scheme: dark) {\n${block(sel(":not([data-theme='light'])"), resolved(name, 'dark'), 'dark')
    .split('\n')
    .map((l) => (l ? '  ' + l : l))
    .join('\n')}}\n\n`;
  css += block(sel("[data-theme='dark']"), resolved(name, 'dark'), 'dark') + '\n';
}
writeFileSync(new URL('../src/styles/palettes.css', import.meta.url), css);
console.log('palettes.css written:', Object.keys(PALETTES).join(', '));
